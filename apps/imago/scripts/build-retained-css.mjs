import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';

const appRoot = path.resolve(import.meta.dirname, '..');
const classicSource = path.resolve(appRoot, '../web/src/app/globals.css');
const source = path.join(appRoot, 'src/retained-adapters/retained.source.css');
let css = await readFile(classicSource, 'utf8');
css = css.replace('../styles/tiptap.css', '../retained/styles/tiptap.css');
// Explicit scan of retained features, not the classic application shell.
css = css.replace('@import "tailwindcss";', '@import "tailwindcss" source(none);');
css += '\n@plugin "../../node_modules/@tailwindcss/typography";\n';
css += `\n@source "${path.join(appRoot, 'src/retained')}";\n@source "${path.join(appRoot, 'src/retained-adapters')}";\n`;
css += `
@theme inline { --color-destructive-foreground: #fff; }
/* Imago C v3 palette (IMC-1.2): the same names imago's own utilities use, so a
   re-skinned classic component reads bg-spine, bg-tint, text-type-doc... The
   values live once, on imago's :root (src/app/theme/v3.css). */
@theme inline {
  --color-spine: var(--spine); --color-spine-ink: var(--spine-ink); --color-tint: var(--tint);
  --color-tab-bar: var(--tab-bar); --color-fill: var(--fill); --color-accent-deep: var(--accent-deep);
  --color-status-success: var(--status-success); --color-status-warning: var(--status-warning);
  --color-status-warning-ink: var(--status-warning-ink); --color-status-danger: var(--status-danger);
  --color-badge: var(--badge); --color-badge-ink: var(--badge-ink);
  --color-type-doc: var(--type-doc); --color-type-tasks: var(--type-tasks); --color-type-sheet: var(--type-sheet);
  --color-type-channel: var(--type-channel); --color-type-folder: var(--type-folder); --color-type-agent: var(--type-agent);
  --color-type-canvas: var(--type-canvas); --color-type-code: var(--type-code); --color-type-file: var(--type-file);
}
.dark { color-scheme: dark; }
.retained-ui { isolation: isolate; }
.middle-section-scroll { overflow-y: auto; }
.editor-readonly { cursor: default; }
.find-highlight { background-color: #fef08a; }
.find-highlight-current { background-color: #fbbf24; }
.prose-xs { font-size: .75rem; }
.prose-red { --tw-prose-body: var(--color-red-700); }
.holographic-card { position: relative; }
`;
await writeFile(source, css);
const result = await postcss([tailwind({ base: appRoot, optimize: false })]).process(css, { from: source });
const root = result.root;
const scoped = postcss.atRule({ name: 'scope', params: '(.retained-ui)' });
const output = postcss.root();
root.walkRules(rule => {
  rule.selector = rule.selector.replace(/:root\b/g, ':scope').replace(/\bhtml\b/g, ':scope').replace(/\bbody\b/g, ':scope');
  if (rule.selector === '.dark') rule.selector = ':scope.dark';
});
for (const node of [...root.nodes]) {
  if (node.type === 'atrule' && ['property', 'keyframes', '-webkit-keyframes', 'charset', 'layer'].includes(node.name) && (node.name !== 'layer' || !node.nodes)) output.append(node);
  else scoped.append(node);
}
output.append(scoped);
output.append(postcss.parse(`
@scope (.retained-ui) {
  :scope {
    --font-sans: var(--font-body);
    --font-mono: var(--font-face-mono), monospace;
    font-family: var(--font-body);
    font-size: 14px;
    color: var(--foreground);
    line-height: 1.6;
  }
}
`));
await writeFile(path.join(appRoot, 'src/retained-adapters/retained.generated.css'), `/* Generated by scripts/build-retained-css.mjs; scoped classic feature styles. */\n${output.toString()}\n`);
console.log('Built scoped retained styles');
